import assert from 'node:assert/strict';
import { rng } from '../js/sim.js';
import { LinUcbCore, standardizeMbonRates } from './package_recovery_linucb.mjs';

const c=new LinUcbCore(), f=[1,-.5,.25], initial=c.predict(f);
assert.deepEqual(initial.means,[0,0,0]);
assert.ok(initial.uncertainty.every(v=>v>0 && Number.isFinite(v)));
assert.equal(c.choose(f,true).action,0);
c.update(-.4);
assert.deepEqual(c.n,[1,0,0]);
assert.ok(c.predict(f).uncertainty[0]<initial.uncertainty[0]);
assert.equal(c.predict(f).uncertainty[1],initial.uncertainty[1]);
assert.equal(c.choose(f,true).action,1);
c.update(-.4);
assert.equal(c.choose(f,true).action,2);
c.update(1);
assert.deepEqual(c.n,[1,1,1]);
const saved=JSON.stringify(c.snapshot());
const frozen=c.choose(f,false);
assert.ok(frozen.bonuses.every(v=>v===0));
assert.equal(frozen.action,frozen.means.indexOf(Math.max(...frozen.means)));
assert.equal(JSON.stringify(c.snapshot()),saved);
const copy=new LinUcbCore(); copy.restore(JSON.parse(saved));
assert.deepEqual(copy.choose(f,false),frozen);
assert.deepEqual(standardizeMbonRates([0,1,3],[0,0,0],[1,1,1]),[0,Math.log(2),Math.log(4)]);
assert.throws(()=>standardizeMbonRates([-1,0,0],[0,0,0],[1,1,1]));
assert.throws(()=>new LinUcbCore({bonus:.6}));
const sample=()=>{const a=new LinUcbCore(), random=rng(15001), out=[];
  for(let i=0;i<12;i++) {const x=[random(),random(),random()];out.push(a.choose(x,true).action);a.update(random()-.5);}return [out,a.snapshot()];};
assert.deepEqual(sample(),sample());
console.log('LinUCB implementation checks passed: action, uncertainty, update, neural features, frozen mode, reproducibility');
