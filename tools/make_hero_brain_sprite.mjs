// Builds js/hero_brain_points.js: a small, evenly strided sample of the real
// soma positions in data/brain_points_3d.bin (brain only, nerve cord cropped),
// projected to a front view (viewer x across, depth down) for the decorative
// "fly becomes a brain" effect in the hero. No positions are synthesized.
// Run: node tools/make_hero_brain_sprite.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const buf = readFileSync(new URL('../data/brain_points_3d.bin', import.meta.url));
const p = new Float32Array(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length));
const BRAIN_MIN_Y = 0.68; // viewer y above the gap to the nerve cord
const brain = [];
for (let i = 0; i < p.length; i += 3) if (p[i + 1] > BRAIN_MIN_Y) brain.push([p[i], p[i + 2]]);
const range = k => [Math.min(...brain.map(q => q[k])), Math.max(...brain.map(q => q[k]))];
const [x0, x1] = range(0), [z0, z1] = range(1);
const TARGET = 1400, stride = Math.max(1, Math.floor(brain.length / TARGET));
const bytes = [];
for (let i = 0; i < brain.length; i += stride)
  bytes.push(Math.round((brain[i][0] - x0) / (x1 - x0) * 255), Math.round((brain[i][1] - z0) / (z1 - z0) * 255));
const aspect = (z1 - z0) / (x1 - x0); // height / width
writeFileSync(new URL('../js/hero_brain_points.js', import.meta.url),
  `// Generated by tools/make_hero_brain_sprite.mjs from data/brain_points_3d.bin (front view).\n` +
  `// ${bytes.length / 2} of ${brain.length} brain somata (every ${stride}th), x/y quantized to 0-255.\n` +
  `export const BRAIN_ASPECT = ${aspect.toFixed(4)};\n` +
  `export const BRAIN_POINTS = '${Buffer.from(bytes).toString('base64')}';\n`);
console.log(`${bytes.length / 2} points, aspect ${aspect.toFixed(3)}`);
